import Foundation

// MARK: - Which files are captures

enum CaptureFileKind: Equatable {
    case image
    case video

    static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic"]
    static let videoExtensions: Set<String> = ["mov", "mp4"]

    /// nil for hidden files (macOS writes a recording to a hidden temp name first and renames it when the
    /// recording is finalized) and for every other file type.
    static func kind(forFileName name: String) -> CaptureFileKind? {
        guard !name.hasPrefix(".") else { return nil }
        let ext = (name as NSString).pathExtension.lowercased()
        if imageExtensions.contains(ext) { return .image }
        if videoExtensions.contains(ext) { return .video }
        return nil
    }
}

// MARK: - Waiting for a file to be finished

enum CaptureFileStability {
    /// Polls until the file has the same non-zero size for `stablePolls` polls in a row AND `finalCheck`
    /// agrees (for a recording: the movie can be opened, i.e. its index has been written). Returns false
    /// when the file disappears or `timeout` seconds pass first.
    static func waitUntilFinalized(
        _ url: URL,
        pollInterval: TimeInterval = 0.5,
        stablePolls: Int = 2,
        timeout: TimeInterval = 90,
        finalCheck: @Sendable (URL) async -> Bool = { _ in true }
    ) async -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        var lastSize = -1
        var stableCount = 0
        while Date() < deadline {
            guard FileManager.default.fileExists(atPath: url.path) else { return false }
            // attributesOfItem, not URL.resourceValues: a URL caches its resource values, so a reused URL
            // would keep answering with the first size it saw and a growing file would look stable.
            let size = ((try? FileManager.default.attributesOfItem(atPath: url.path))?[.size] as? NSNumber)?.intValue ?? 0
            if size > 0 && size == lastSize {
                stableCount += 1
            } else {
                stableCount = 0
            }
            lastSize = size
            if stableCount >= stablePolls, await finalCheck(url) { return true }
            try? await Task.sleep(nanoseconds: UInt64(pollInterval * 1_000_000_000))
            if Task.isCancelled { return false }
        }
        return false
    }
}

// MARK: - Clipboard images

struct ClipboardImage {
    let png: Data
    let pixelSize: CGSize
}

/// Watches ONE pasteboard (the general one in the app, a private named one in the tests) and reports each
/// new image put on it. The caller drives it with `poll()` on a light timer.
final class PasteboardImageMonitor {
    /// Images smaller than this on both sides are icons and the like, not screenshots.
    static let minimumSide: CGFloat = 24
    /// Raw size above which an image is ignored (a copied 100 MP photo is not a screenshot).
    static let maximumBytes = 80_000_000

    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
    private static let fileTypes: Set<String> = ["public.file-url", "NSFilenamesPboardType"]

    private let pasteboard: NSPasteboard
    private(set) var lastChangeCount: Int
    private var lastDigest: SHA256.Digest?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    /// Forget what is on the pasteboard right now (it will not be reported).
    func rebaseline() {
        lastChangeCount = pasteboard.changeCount
        lastDigest = nil
    }

    /// The new image, if the pasteboard changed since the last poll and now holds one.
    func poll() -> ClipboardImage? {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return nil }
        lastChangeCount = count
        guard let types = pasteboard.types else { return nil }
        let names = Set(types.map(\.rawValue))
        // Copied files (Finder puts a file icon image next to the file URL) and password-manager style
        // markers are not captures.
        if !names.isDisjoint(with: Self.fileTypes) || !names.isDisjoint(with: Self.concealedTypes) { return nil }

        let imageTypes: [NSPasteboard.PasteboardType] = [
            .png, .tiff, NSPasteboard.PasteboardType("public.jpeg"), NSPasteboard.PasteboardType("public.heic"),
        ]
        guard let type = imageTypes.first(where: { names.contains($0.rawValue) }) else {
            lastDigest = nil // something else was copied: the same image copied later is new again
            return nil
        }
        guard let data = pasteboard.data(forType: type),
              !data.isEmpty, data.count <= Self.maximumBytes else { return nil }

        let digest = SHA256.hash(data: data)
        if let last = lastDigest, last == digest { return nil } // the same image copied again
        guard let rep = NSBitmapImageRep(data: data) else { return nil }
        let size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        guard max(size.width, size.height) >= Self.minimumSide else { return nil }
        let png: Data
        if type == .png {
            png = data
        } else if let converted = rep.representation(using: .png, properties: [:]) {
            png = converted
        } else {
            return nil
        }
        lastDigest = digest
        return ClipboardImage(png: png, pixelSize: size)
    }
}

// MARK: - Keeping the newest N

enum CapturePruner {
    struct Result: Equatable {
        /// Auto-added ids still on the shelf after pruning, oldest first.
        var kept: [UUID]
        /// The ones to remove from the shelf (oldest first).
        var remove: [UUID]
    }

    /// `order`: ids of auto-added captures, oldest first. `present`: ids of the items currently on the
    /// shelf (a capture the user already removed just drops out of the list). Items that are not in `order`
    /// are never touched, so user-added items are safe by construction.
    static func prune(order: [UUID], present: Set<UUID>, keep: Int) -> Result {
        var seen = Set<UUID>()
        var live = order.filter { present.contains($0) && seen.insert($0).inserted }
        let limit = max(1, keep)
        var removed: [UUID] = []
        while live.count > limit {
            removed.append(live.removeFirst())
        }
        return Result(kept: live, remove: removed)
    }
}

// MARK: - Labels

enum CaptureLabel {
    /// "0:12", "12:03", "1:02:03".
    static func duration(_ seconds: TimeInterval) -> String {
        let total = max(0, Int(seconds.rounded()))
        let h = total / 3600, m = (total % 3600) / 60, s = total % 60
        return h > 0 ? String(format: "%d:%02d:%02d", h, m, s) : String(format: "%d:%02d", m, s)
    }
}
